import assert from 'node:assert/strict';
import React from 'react';
import {renderToStaticMarkup} from 'react-dom/server';
import {NotificationRelay,recordNotificationEvidence,notificationEvidence,notificationEvidenceReport} from '../src/services/notificationEvidence';
import {NotificationEvidencePanel} from '../src/components/NotificationEvidencePanel';
const memory=new Map<string,string>();
Object.defineProperty(globalThis,'localStorage',{configurable:true,value:{getItem:(k:string)=>memory.get(k)||null,setItem:(k:string,v:string)=>memory.set(k,v)}});
const relay=new NotificationRelay(),seen:string[]=[];
relay.emit({eventId:'cold'},'opened');
const remove=relay.subscribe((p,o)=>seen.push(`${p.eventId}:${o}`));
assert.deepEqual(seen,['cold:opened'],'Cold-start click must reach subscriber');
remove();relay.emit({eventId:'warm'},'received');
const remove2=relay.subscribe((p,o)=>seen.push(`${p.eventId}:${o}`));
assert.deepEqual(seen,['cold:opened','warm:received']);
remove2();relay.subscribe((p,o)=>seen.push(`${p.eventId}:${o}`));
assert.equal(seen.length,2,'Resubscription does not replay already delivered callbacks');
recordNotificationEvidence({eventId:'test-1',eventType:'DIAGNOSTIC_TEST',token:'PRIVATE',body:'PRIVATE'},'opened',1234);
recordNotificationEvidence({eventId:'test-1',eventType:'DIAGNOSTIC_TEST'},'opened',2345);
assert.equal(notificationEvidence().length,1);
assert.equal(notificationEvidence()[0].clientAtMs,1234);
assert.ok(!JSON.stringify(notificationEvidenceReport()).includes('PRIVATE'));
assert.equal(notificationEvidenceReport().serverDeliveryVerified,false);
let html=renderToStaticMarkup(<NotificationEvidencePanel/>);
assert.ok(html.includes('点击通知'));assert.ok(html.includes('没有接收回调不代表锁屏未送达'));
for(let i=0;i<310;i++)recordNotificationEvidence({eventId:`e${i}`},'received',10000+i);
assert.equal(notificationEvidence().length,300);
assert.equal(notificationEvidence()[0].id,'e10');
console.log('Notification evidence: cold-start replay, resubscribe, dedupe, privacy, bounded retention and truthful labels passed.');
